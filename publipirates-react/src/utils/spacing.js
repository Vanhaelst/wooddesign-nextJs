const KEYS = Object.keys(SPACING);

// Returns the Tailwind classes for the spacing props (m, mt, px, ...) and the
// remaining props, so callers can spread the rest onto the DOM element.
export const spacingProps = (props) => {
  const rest = {};
  const classes = [];
  for (const key of Object.keys(props)) {
    if (KEYS.includes(key)) {
      const cls = SPACING[key][props[key]];
      if (cls) classes.push(cls);
    } else {
      rest[key] = props[key];
    }
  }
  return [classes.join(" "), rest];
};
